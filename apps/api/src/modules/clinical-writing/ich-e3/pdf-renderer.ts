// ICH E3 compliance report as a PDF (CW-040): the section checklist with each section's status, the
// waivers with who / when / why / which version, and who generated it. Built on the server so the browser
// gets a real file an auditor can keep. pdfkit's built-in Helvetica covers Latin text; pdfSafeText turns
// anything else into "?" rather than corrupting the page.

import PDFDocument from 'pdfkit'
import { pdfSafeText } from '../../platform/library/pdf-renderer.js'
import type { IchE3Report } from './catalog.js'

const STATUS_LABEL: Record<string, string> = {
  complete: 'Complete', in_progress: 'In progress', not_started: 'Not started', waived: 'Waived', warning: 'Needs attention',
}

const day = (iso: string | Date) => new Date(iso).toISOString().slice(0, 10)

export function renderIchE3Pdf(args: { report: IchE3Report; generatedBy: string; generatedAt: Date }): Promise<Buffer> {
  const { report } = args
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: 'A4', margins: { top: 54, bottom: 60, left: 48, right: 48 }, bufferPages: true,
      info: { Title: pdfSafeText(`ICH E3 compliance report - ${report.documentTitle}`), Author: 'ClinWrite.AI' },
    })
    const chunks: Buffer[] = []
    doc.on('data', (c: Buffer) => chunks.push(c))
    doc.on('end', () => resolve(Buffer.concat(chunks)))
    doc.on('error', reject)

    const width = doc.page.width - doc.page.margins.left - doc.page.margins.right
    doc.font('Helvetica-Bold').fontSize(16).fillColor('#0F172A').text('ICH E3 compliance report')
    doc.moveDown(0.3).font('Helvetica').fontSize(11).fillColor('#334155')
      .text(pdfSafeText(`Document: ${report.documentTitle}`))
      .text(`Generated by ${pdfSafeText(args.generatedBy)} on ${args.generatedAt.toISOString().replace('T', ' ').slice(0, 19)} UTC`)
      .text(`Completion: ${report.completionPercent}% (${report.completeCount} complete, ${report.waivedCount} waived, of ${report.totalSections} sections)`)
    doc.moveDown(0.8)

    // Section table
    const cols = [{ w: 52, t: 'Section' }, { w: width - 52 - 90 - 140, t: 'Title' }, { w: 90, t: 'Status' }, { w: 140, t: 'Notes' }]
    const drawRow = (cells: string[], bold = false, fill?: string) => {
      const y = doc.y
      const heights = cells.map((c, i) => doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(9).heightOfString(c, { width: cols[i]!.w - 6 }))
      const h = Math.max(...heights) + 6
      if (y + h > doc.page.height - doc.page.margins.bottom) { doc.addPage(); return drawRow(cells, bold, fill) }
      if (fill) doc.save().rect(doc.page.margins.left, y, width, h).fill(fill).restore()
      let x = doc.page.margins.left
      cells.forEach((c, i) => {
        doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(9).fillColor('#0F172A').text(c, x + 3, y + 3, { width: cols[i]!.w - 6 })
        x += cols[i]!.w
      })
      doc.moveTo(doc.page.margins.left, y + h).lineTo(doc.page.margins.left + width, y + h).strokeColor('#E2E8F0').lineWidth(0.5).stroke()
      doc.x = doc.page.margins.left; doc.y = y + h
    }
    drawRow(cols.map(c => c.t), true, '#F1F5F9')
    for (const s of report.sections) {
      const notes = [s.conditional ? 'US only' : '', s.inDocument ? '' : 'Not in document', s.waiver ? 'Waiver recorded' : ''].filter(Boolean).join(', ')
      drawRow([s.code, pdfSafeText(s.title), STATUS_LABEL[s.status] ?? s.status, notes])
    }

    // Waivers
    const waived = report.sections.filter(s => s.waiver)
    doc.moveDown(1.2)
    doc.font('Helvetica-Bold').fontSize(12).fillColor('#0F172A').text('Waivers')
    doc.moveDown(0.3)
    if (waived.length === 0) doc.font('Helvetica').fontSize(10).fillColor('#475569').text('No section has been waived.')
    for (const s of waived) {
      const w = s.waiver!
      if (doc.y > doc.page.height - doc.page.margins.bottom - 70) doc.addPage()
      doc.font('Helvetica-Bold').fontSize(10).fillColor('#0F172A').text(pdfSafeText(`${s.code} ${s.title}`))
      doc.font('Helvetica').fontSize(9.5).fillColor('#334155')
        .text(`Waived by ${pdfSafeText(w.waivedByName ?? 'unknown user')} on ${day(w.waivedAt)}, at ${pdfSafeText(w.versionAtWaiver)}`)
        .text(pdfSafeText(`Reason: ${w.reason}`))
      doc.moveDown(0.5)
    }

    // Page numbers
    const range = doc.bufferedPageRange()
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i)
      doc.font('Helvetica').fontSize(8).fillColor('#94A3B8')
        .text(`Page ${i + 1} of ${range.count}`, doc.page.margins.left, doc.page.height - 40, { width, align: 'center' })
    }
    doc.end()
  })
}
